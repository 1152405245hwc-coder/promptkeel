#!/usr/bin/env node
// Wrap the hand-written client entry into the DSH module-loader bundle format.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = path.join(root, "client/src/entry.js");
const outPath = path.join(root, "client/client.js");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));

let src = fs.readFileSync(srcPath, "utf8");
// The loader provides CommonJS-style require(); strip ESM export keywords.
src = src.replace(/^export const /gm, "const ").replace(/^export function /gm, "function ");
src += `\nmodule.exports = { name, inject, apply };\n`;

const bundle = `// Generated by scripts/build-client.mjs — do not edit.
// PromptKeel v${pkg.version} client bundle. MIT.
(() => {
  const __FORGE_MODULE_URL__ = typeof document !== "undefined" ? document.currentScript?.src : undefined;
  window.__ModuleLoader__.load({
    id: "promptkeel",
    factory: (require) => {
      var module = { exports: {} };
      var exports = module.exports;
${src}
      return module.exports;
    },
  });
})();
`;

fs.writeFileSync(outPath, bundle);
const bytes = Buffer.byteLength(bundle);
process.stdout.write(`built ${path.relative(root, outPath)} · ${bytes} bytes\n`);
